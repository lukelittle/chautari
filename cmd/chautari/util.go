package main

import (
	"encoding/json"
	"net/http"

	"github.com/lukelittle/chautari/internal/ui"
)

func mustJSON(v any) []byte {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		panic(err)
	}
	return append(b, '\n')
}

// uiHandler serves the embedded admin UI.
func uiHandler() http.Handler { return ui.Handler() }
